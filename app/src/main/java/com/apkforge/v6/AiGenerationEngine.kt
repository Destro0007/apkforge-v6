
package com.apkforge.v6

data class AiGenerationRequest(
    val projectName: String,
    val packageName: String,
    val description: String
)

data class GeneratedProjectFile(
    val fileName: String,
    val content: String
)

data class AiGenerationResult(
    val providerName: String,
    val summary: String,
    val files: List<GeneratedProjectFile>
)

interface AiCodeProvider {
    val displayName: String

    suspend fun generate(
        request: AiGenerationRequest
    ): AiGenerationResult
}

/**
 * Offline starter provider.
 * This uses deterministic templates, not an AI model.
 */
class OfflineTemplateProvider : AiCodeProvider {

    override val displayName: String =
        "Offline starter generator"

    override suspend fun generate(
        request: AiGenerationRequest
    ): AiGenerationResult {
        val safePackage = request.packageName.trim()

        require(PACKAGE_PATTERN.matches(safePackage)) {
            "Enter a valid package name, such as com.example.myapp"
        }

        val cleanName = request.projectName.trim()
            .ifBlank { "My APKForge App" }

        val cleanDescription = request.description.trim()
            .ifBlank {
                "A new Android application created with APKForge V6."
            }

        // Escape characters that could break the generated Kotlin string.
        val safeTitle = cleanName
            .replace("\\", "\\\\")
            .replace("\"", "\\\"")
            .replace("$", "\\$")
            .replace("\r", " ")
            .replace("\n", " ")

        val activity = """
            package $safePackage

            import android.os.Bundle
            import android.widget.TextView
            import androidx.activity.ComponentActivity

            class MainActivity : ComponentActivity() {
                override fun onCreate(savedInstanceState: Bundle?) {
                    super.onCreate(savedInstanceState)

                    val message = TextView(this).apply {
                        text = "$safeTitle"
                        textSize = 24f
                        setPadding(32, 48, 32, 32)
                    }

                    setContentView(message)
                }
            }
        """.trimIndent() + "\n"

        val readme = """
            # $cleanName

            $cleanDescription

            ## Package
            `$safePackage`

            ## Generated by
            APKForge V6 - Offline starter generator

            This is a deterministic starter template.
            Connect an AI model provider to generate
            application-specific screens and logic.
        """.trimIndent() + "\n"

        return AiGenerationResult(
            providerName = displayName,
            summary = "Created an Android starter project using offline templates. This is not AI-generated code.",
            files = listOf(
                GeneratedProjectFile(
                    "MainActivity.kt",
                    activity
                ),
                GeneratedProjectFile(
                    "README.md",
                    readme
                )
            )
        )
    }

    private companion object {
        val PACKAGE_PATTERN = Regex(
            "[A-Za-z_][A-Za-z0-9_]*(\\.[A-Za-z_][A-Za-z0-9_]*)+"
        )
    }
}
